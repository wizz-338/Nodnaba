"""Build Mano Colony game assets from the original sheets.

    python3 scripts/colony-assets.py

Reads assets-src/colony/manifest.json and the untouched originals in
assets-src/colony/originals/, writes cleaned, cut, resized and packed
assets into src/colony/assets/. The outputs are committed, so the site
build never needs Python. Needs Pillow, numpy and scipy.
"""
import json
import os
import sys

import numpy as np
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from colony_assets_lib import ALPHA_CUT, cells, clean, cut, head_x, pack, resize  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..')
SRC = os.path.join(ROOT, 'assets-src/colony')
OUT = os.path.join(ROOT, 'src/colony/assets')

# Mano is cut from three sheets drawn at the same size: one scale for all of
# them keeps her the same height in every animation (36 world px tall).
MANO_WORLD_H = 36
MANO_SRC_H = 268


def seamless(img):
    """Blend a half-offset copy in near the edges so the texture wraps."""
    a = img.astype(float)
    h, w = a.shape[:2]
    b = np.roll(np.roll(a, h // 2, 0), w // 2, 1)
    yy, xx = np.mgrid[0:h, 0:w]
    # 0 in the middle, 1 at the edges (where the original does not wrap)
    d = np.maximum(np.abs(yy - (h - 1) / 2) / (h / 2), np.abs(xx - (w - 1) / 2) / (w / 2))
    m = np.clip((d - 0.55) / 0.4, 0, 1)[..., None]
    return (a * (1 - m) + b * m).round().astype(np.uint8)


def main():
    man = json.load(open(os.path.join(SRC, 'manifest.json')))
    S = man['scale']
    atlases = {}  # out path -> {name: (img, anchor, src)}
    for sheet_name, sh in man['sheets'].items():
        path = os.path.join(SRC, 'originals', sh['file'])
        rows, cols = sh['grid']
        kind = sh['kind']
        print('·', sheet_name, kind)

        if kind == 'texture':
            im = Image.open(path).convert('RGB')
            W, H = im.size
            os.makedirs(os.path.join(OUT, sh['out']), exist_ok=True)
            for key, name in sh['cells'].items():
                r, c = map(int, key.split(','))
                i = sh['inset']
                box = (round(c * W / cols) + i, round(r * H / rows) + i,
                       round((c + 1) * W / cols) - i, round((r + 1) * H / rows) - i)
                t = np.array(im.crop(box).resize((sh['size'], sh['size']), Image.LANCZOS))
                Image.fromarray(seamless(t)).save(os.path.join(OUT, sh['out'], name + '.png'), optimize=True)
            continue

        a = clean(path, sh.get('minPx', 150))
        found = cells(a, cols, rows, dilate=sh.get('dilate', 3), min_px=sh.get('cellMin', 1500))
        for key, spec in sh['cells'].items():
            r, c = map(int, key.split(','))
            if (r, c) not in found:
                raise SystemExit(f'{sheet_name}: nothing found in cell {key}')
            img, src = cut(a, found[(r, c)])
            if kind == 'character':
                name = spec
                small = resize(img, MANO_WORLD_H / MANO_SRC_H * S)
                anchor = (head_x(small), small.shape[0])  # head centre, feet
            elif kind == 'icon':
                name = spec
                n = sh['size']
                k = n / max(img.shape[:2])
                small = resize(img, k)
                canvas = np.zeros((n, n, 4), np.uint8)
                y0 = (n - small.shape[0]) // 2
                x0 = (n - small.shape[1]) // 2
                canvas[y0:y0 + small.shape[0], x0:x0 + small.shape[1]] = small
                os.makedirs(os.path.join(OUT, sh['out']), exist_ok=True)
                Image.fromarray(canvas, 'RGBA').save(os.path.join(OUT, sh['out'], name + '.png'), optimize=True)
                continue
            else:
                name, world_w = spec
                small = resize(img, world_w * S / img.shape[1])
                anchor = (small.shape[1] / 2, small.shape[0])  # bottom centre
            atlases.setdefault(sh['out'], {})[name] = (small, anchor, src, sheet_name)

    for out, items in atlases.items():
        atlas, pos = pack({k: v[0] for k, v in items.items()})
        os.makedirs(os.path.dirname(os.path.join(OUT, out)), exist_ok=True)
        # a 256-colour palette looks the same here and is ~4x smaller
        im = Image.fromarray(atlas, 'RGBA').quantize(256, method=Image.Quantize.FASTOCTREE,
                                                      dither=Image.Dither.FLOYDSTEINBERG)
        im.save(os.path.join(OUT, out + '.png'), optimize=True)
        frames = {}
        for k in sorted(items):
            x, y, w, h = pos[k]
            _, (ax, ay), src, sheet = items[k]
            frames[k] = {'x': x, 'y': y, 'w': w, 'h': h, 'ax': round(ax, 1), 'ay': round(ay, 1),
                         'from': sheet, 'src': list(src)}
        meta = {'_about': 'generated by scripts/colony-assets.py — do not edit by hand',
                'scale': S, 'alphaCut': ALPHA_CUT, 'frames': frames}
        json.dump(meta, open(os.path.join(OUT, out + '.json'), 'w'), indent=1)
        print(f'  {out}.png {atlas.shape[1]}x{atlas.shape[0]}  {len(items)} frames')


if __name__ == '__main__':
    main()
